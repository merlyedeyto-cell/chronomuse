-- All tables prefixed with chronomuse_

-- Enable UUID extension just in case
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Create standard function for updating updated_at timestamp
CREATE OR REPLACE FUNCTION update_modified_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ language 'plpgsql';

-- --------------------------------------------------------
-- Table structure for table chronomuse_users
-- --------------------------------------------------------

CREATE TABLE chronomuse_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(50) NOT NULL UNIQUE,
  email varchar(100) NOT NULL UNIQUE,
  password varchar(255) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_activity timestamptz DEFAULT NULL
);

CREATE TRIGGER update_chronomuse_users_modtime
    BEFORE UPDATE ON chronomuse_users
    FOR EACH ROW
    EXECUTE FUNCTION update_modified_column();

-- --------------------------------------------------------
-- Table structure for table chronomuse_memories
-- --------------------------------------------------------

CREATE TABLE chronomuse_memories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  date date NOT NULL,
  title varchar(255) NOT NULL,
  description text DEFAULT NULL,
  mood_tag varchar(50) DEFAULT NULL,
  memory_tag varchar(100) DEFAULT NULL,
  photo_video varchar(500) DEFAULT NULL,
  photo_video_type varchar(100) DEFAULT NULL,
  music varchar(500) DEFAULT NULL,
  is_pinned boolean DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_chronomuse_memories_user_date ON chronomuse_memories (user_id, date);
CREATE INDEX idx_chronomuse_memories_date ON chronomuse_memories (date);

CREATE TRIGGER update_chronomuse_memories_modtime
    BEFORE UPDATE ON chronomuse_memories
    FOR EACH ROW
    EXECUTE FUNCTION update_modified_column();

-- --------------------------------------------------------
-- Table structure for table chronomuse_memory_tags
-- --------------------------------------------------------

CREATE TABLE chronomuse_memory_tags (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  memory_id bigint NOT NULL REFERENCES chronomuse_memories(id) ON DELETE CASCADE,
  tag varchar(100) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_chronomuse_mem_tags_memory ON chronomuse_memory_tags (memory_id);

-- --------------------------------------------------------
-- Table structure for table chronomuse_pinned_dates
-- --------------------------------------------------------

CREATE TABLE chronomuse_pinned_dates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  date date NOT NULL,
  title varchar(255) DEFAULT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_chronomuse_user_date UNIQUE (user_id, date)
);

CREATE INDEX idx_chronomuse_pinned_dates_user ON chronomuse_pinned_dates (user_id);
CREATE INDEX idx_chronomuse_pinned_dates_date ON chronomuse_pinned_dates (date);

-- --------------------------------------------------------
-- Table structure for table chronomuse_pinned_memories
-- --------------------------------------------------------

CREATE TABLE chronomuse_pinned_memories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  memory_id bigint NOT NULL REFERENCES chronomuse_memories(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_chronomuse_pin UNIQUE (user_id, memory_id)
);

CREATE INDEX idx_chronomuse_pinned_mem_memory ON chronomuse_pinned_memories (memory_id);
CREATE INDEX idx_chronomuse_pinned_mem_user ON chronomuse_pinned_memories (user_id);

