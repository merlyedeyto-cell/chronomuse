-- --------------------------------------------------------
-- Table structure for friend requests
-- --------------------------------------------------------

CREATE TABLE IF NOT EXISTS chronomuse_friend_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  receiver_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  status varchar(20) NOT NULL DEFAULT 'pending', -- pending, accepted, declined
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_friend_request UNIQUE (sender_id, receiver_id)
);

-- --------------------------------------------------------
-- Table structure for accepted friends
-- --------------------------------------------------------

CREATE TABLE IF NOT EXISTS chronomuse_friends (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  friend_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_friendship UNIQUE (user_id, friend_id)
);

CREATE INDEX IF NOT EXISTS idx_chronomuse_friends_user ON chronomuse_friends (user_id);
CREATE INDEX IF NOT EXISTS idx_chronomuse_friends_friend ON chronomuse_friends (friend_id);

-- --------------------------------------------------------
-- Table structure for chat messages
-- --------------------------------------------------------

CREATE TABLE IF NOT EXISTS chronomuse_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  receiver_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  message text NOT NULL,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_chronomuse_messages_sender_receiver ON chronomuse_messages (sender_id, receiver_id);

-- --------------------------------------------------------
-- Table structure for shared / tagged memories
-- --------------------------------------------------------

CREATE TABLE IF NOT EXISTS chronomuse_shared_memories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  memory_id bigint NOT NULL REFERENCES chronomuse_memories(id) ON DELETE CASCADE,
  sender_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  recipient_id bigint NOT NULL REFERENCES chronomuse_users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_shared_memory UNIQUE (memory_id, recipient_id)
);

CREATE INDEX IF NOT EXISTS idx_chronomuse_shared_memories_recipient ON chronomuse_shared_memories (recipient_id);

-- Disable Row Level Security (RLS) on all new tables for direct API access
ALTER TABLE chronomuse_friend_requests DISABLE ROW LEVEL SECURITY;
ALTER TABLE chronomuse_friends DISABLE ROW LEVEL SECURITY;
ALTER TABLE chronomuse_messages DISABLE ROW LEVEL SECURITY;
ALTER TABLE chronomuse_shared_memories DISABLE ROW LEVEL SECURITY;
