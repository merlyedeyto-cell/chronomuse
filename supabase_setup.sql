-- 1. Enable UUID Extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Create Timestamp Update Trigger Function
CREATE OR REPLACE FUNCTION update_modified_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ language 'plpgsql';

-- --------------------------------------------------------
-- 3. Table: chronomuse_users
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(50) NOT NULL UNIQUE,
  email varchar(100) NOT NULL UNIQUE,
  password varchar(255) NOT NULL,
  avatar_url varchar(500) DEFAULT NULL,
  cover_url varchar(500) DEFAULT NULL,
  bio text DEFAULT NULL,
  birthday date DEFAULT NULL,
  relationship_status varchar(50) DEFAULT NULL,
  gender varchar(50) DEFAULT NULL,
  note varchar(100) DEFAULT NULL,
  is_private boolean DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_activity timestamptz DEFAULT NULL,
  status varchar(20) NOT NULL DEFAULT 'active'
);

DROP TRIGGER IF EXISTS update_chronomuse_users_modtime ON public.chronomuse_users;
CREATE TRIGGER update_chronomuse_users_modtime
    BEFORE UPDATE ON public.chronomuse_users
    FOR EACH ROW
    EXECUTE FUNCTION update_modified_column();

-- --------------------------------------------------------
-- 4. Table: chronomuse_memories
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_memories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  date date NOT NULL,
  title varchar(255) NOT NULL,
  description text DEFAULT NULL,
  mood_tag varchar(50) DEFAULT NULL,
  memory_tag varchar(100) DEFAULT NULL,
  photo_video varchar(500) DEFAULT NULL,
  photo_video_type varchar(100) DEFAULT NULL,
  music varchar(500) DEFAULT NULL,
  is_pinned boolean DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

DROP TRIGGER IF EXISTS update_chronomuse_memories_modtime ON public.chronomuse_memories;
CREATE TRIGGER update_chronomuse_memories_modtime
    BEFORE UPDATE ON public.chronomuse_memories
    FOR EACH ROW
    EXECUTE FUNCTION update_modified_column();

-- --------------------------------------------------------
-- 5. Table: chronomuse_memory_tags
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_memory_tags (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  memory_id bigint NOT NULL REFERENCES public.chronomuse_memories(id) ON DELETE CASCADE,
  tag varchar(100) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- --------------------------------------------------------
-- 6. Table: chronomuse_pinned_dates
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_pinned_dates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  date date NOT NULL,
  title varchar(255) DEFAULT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_chronomuse_user_date UNIQUE (user_id, date)
);

-- --------------------------------------------------------
-- 7. Table: chronomuse_pinned_memories
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_pinned_memories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  memory_id bigint NOT NULL REFERENCES public.chronomuse_memories(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_chronomuse_pin UNIQUE (user_id, memory_id)
);

-- --------------------------------------------------------
-- 8. Table: chronomuse_friends
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_friends (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  friend_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_friendship UNIQUE (user_id, friend_id)
);

-- --------------------------------------------------------
-- 9. Table: chronomuse_friend_requests
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_friend_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  receiver_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  status varchar(20) NOT NULL DEFAULT 'pending',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_friend_request UNIQUE (sender_id, receiver_id)
);

-- --------------------------------------------------------
-- 10. Table: chronomuse_messages
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  receiver_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  message text NOT NULL,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- --------------------------------------------------------
-- 11. Table: chronomuse_shared_memories
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_shared_memories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  memory_id bigint NOT NULL REFERENCES public.chronomuse_memories(id) ON DELETE CASCADE,
  sender_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  recipient_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_shared_memory UNIQUE (memory_id, recipient_id)
);

-- --------------------------------------------------------
-- 12. Table: chronomuse_user_notes
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_user_notes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  note_text varchar(100) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_chronomuse_user_notes UNIQUE (user_id)
);

-- --------------------------------------------------------
-- 13. Table: chronomuse_blocked_users
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_blocked_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  blocker_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  blocked_id bigint NOT NULL REFERENCES public.chronomuse_users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_blocked_user UNIQUE (blocker_id, blocked_id)
);

-- --------------------------------------------------------
-- 14. Table: chronomuse_feedbacks
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.chronomuse_feedbacks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint REFERENCES public.chronomuse_users(id) ON DELETE SET NULL,
  username varchar(50) DEFAULT 'anonymous',
  category varchar(50) NOT NULL DEFAULT 'suggestion',
  title varchar(255) NOT NULL,
  message text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'new',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- =========================================================================
-- HIGH-PERFORMANCE INDEXES
-- =========================================================================

-- Users
CREATE INDEX IF NOT EXISTS idx_chronomuse_users_username_lower ON public.chronomuse_users (LOWER(username));
CREATE INDEX IF NOT EXISTS idx_chronomuse_users_email_lower ON public.chronomuse_users (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_chronomuse_users_last_activity ON public.chronomuse_users (last_activity DESC);

-- Memories
CREATE INDEX IF NOT EXISTS idx_chronomuse_memories_user_date ON public.chronomuse_memories (user_id, date DESC);
CREATE INDEX IF NOT EXISTS idx_chronomuse_memories_user_mood ON public.chronomuse_memories (user_id, mood_tag);
CREATE INDEX IF NOT EXISTS idx_chronomuse_memories_created_at ON public.chronomuse_memories (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_chronomuse_memories_date ON public.chronomuse_memories (date);
CREATE INDEX IF NOT EXISTS idx_chronomuse_mem_tags_memory ON public.chronomuse_memory_tags (memory_id);

-- Pinned Dates & Memories
CREATE INDEX IF NOT EXISTS idx_chronomuse_pinned_dates_user ON public.chronomuse_pinned_dates (user_id, date);
CREATE INDEX IF NOT EXISTS idx_chronomuse_pinned_mem_memory ON public.chronomuse_pinned_memories (memory_id);
CREATE INDEX IF NOT EXISTS idx_chronomuse_pinned_mem_user ON public.chronomuse_pinned_memories (user_id);

-- Messages
CREATE INDEX IF NOT EXISTS idx_chronomuse_messages_sender_receiver ON public.chronomuse_messages (sender_id, receiver_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_chronomuse_messages_receiver_sender ON public.chronomuse_messages (receiver_id, sender_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_chronomuse_messages_receiver_read ON public.chronomuse_messages (receiver_id, is_read);

-- Friends & Requests
CREATE INDEX IF NOT EXISTS idx_chronomuse_friends_user_id ON public.chronomuse_friends (user_id);
CREATE INDEX IF NOT EXISTS idx_chronomuse_friends_friend_id ON public.chronomuse_friends (friend_id);
CREATE INDEX IF NOT EXISTS idx_chronomuse_friend_requests_receiver ON public.chronomuse_friend_requests (receiver_id, status);
CREATE INDEX IF NOT EXISTS idx_chronomuse_friend_requests_sender ON public.chronomuse_friend_requests (sender_id, status);

-- Shared Memories
CREATE INDEX IF NOT EXISTS idx_chronomuse_shared_memories_recipient ON public.chronomuse_shared_memories (recipient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_chronomuse_shared_memories_sender ON public.chronomuse_shared_memories (sender_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_chronomuse_shared_memories_memory ON public.chronomuse_shared_memories (memory_id);

-- Blocked Users
CREATE INDEX IF NOT EXISTS idx_chronomuse_blocked_users_blocker ON public.chronomuse_blocked_users (blocker_id, blocked_id);

-- User Notes
CREATE INDEX IF NOT EXISTS idx_chronomuse_user_notes_user ON public.chronomuse_user_notes (user_id);

